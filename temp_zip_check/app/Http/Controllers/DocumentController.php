    public function index(\Illuminate\Http\Request $request)
    {
        $user = auth()->user();
        if (in_array($user->role, ['superadmin', 'admin'])) {
            $companies = Company::all();
            $companyId = $request->query('company_id');
            $company = $companyId ? Company::find($companyId) : $companies->first();
            $employees = User::where('company_id', $company->id ?? null)->where('role', 'employee')->get();
            $allEmployees = User::where('role', 'employee')->get();
            return view('admin.documents.index', compact('company', 'employees', 'companies', 'allEmployees'));
        } else {
            $company = $user->company;
            $employees = User::where('company_id', $user->company_id)->where('role', 'employee')->get();
            $companies = collect([$company]);
            $allEmployees = $employees;
            return view('admin.documents.index', compact('company', 'employees', 'companies', 'allEmployees'));
        }
    }

    public function generate(Request $request)
    {
        $request->validate([
            'employee_id'              => 'required|exists:users,id',
            'documents'                => 'required|array|min:1',
            'designation'              => 'required|string|max:255',
