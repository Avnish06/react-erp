            'work_location'            => 'required|string|max:255',
            'base_salary'              => 'required|numeric|min:0',
            'currency'                 => 'required|string|max:10',
            'pay_frequency'            => 'required|in:monthly,bi-monthly,weekly',
            'bonus_structure'          => 'nullable|string|max:500',
            'probation_period_months'  => 'required|integer|min:0',
            'notice_period_days'       => 'required|integer|min:0',
            'non_compete_duration_months' => 'required|integer|min:0',
            'non_compete_geographic_scope' => 'required|string|max:255',
            'confidentiality_duration_years' => 'required|integer|min:1',
            'jurisdiction'             => 'required|string|max:255',
            'signatory_name'           => 'required|string|max:255',
            'signatory_title'          => 'required|string|max:255',
            'leave_types'              => 'nullable|array',
        ]);

        $employee  = User::findOrFail($request->employee_id);
        
        // Update employee profile so future documents generated by them will reflect these changes
        $employee->update([
            'department'                     => $request->department,
            'position'                       => $request->designation,
            'salary'                         => $request->base_salary,
            'employment_type'                => $request->employment_type,
            'reporting_manager'              => $request->reporting_manager,
            'work_location'                  => $request->work_location,
            'currency'                       => $request->currency,
            'pay_frequency'                  => $request->pay_frequency,
            'bonus_structure'                => $request->bonus_structure,
            'probation_period_months'        => $request->probation_period_months,
            'notice_period_days'             => $request->notice_period_days,
            'non_compete_duration_months'    => $request->non_compete_duration_months,
            'confidentiality_duration_years' => $request->confidentiality_duration_years,
            'non_compete_geographic_scope'   => $request->non_compete_geographic_scope,
        ]);
        $company   = $employee->company ?? auth()->user()->company;
        $today     = Carbon::today()->format('Y-m-d');

        $data = [
            'company_name'             => $company->name ?? 'Your Company',
            'company_address'          => $company->address ?? 'Plot 93, Rajendra Park, Sector 105, Gurugram � 122001. Haryana',
            'company_logo'             => $company->logo ? asset('storage/' . $company->logo) : '',
            'signatory_name'           => $request->signatory_name,
            'signatory_title'          => $request->signatory_title,
            'employee_name'            => $employee->name,
            'designation'              => $request->designation,
            'department'               => $request->department,
            'employment_type'          => ucfirst($request->employment_type),
            'start_date'               => Carbon::parse($request->start_date)->format('d F Y'),
            'reporting_manager'        => $request->reporting_manager,
            'work_location'            => $request->work_location,
            'base_salary'              => number_format($request->base_salary, 2),
            'currency'                 => $request->currency,
            'pay_frequency'            => ucfirst($request->pay_frequency),
            'bonus_structure'          => $request->bonus_structure ?: 'As per company policy',
            'probation_period_months'  => $request->probation_period_months,
            'notice_period_days'       => $request->notice_period_days,
            'non_compete_duration_months' => $request->non_compete_duration_months,
            'non_compete_geographic_scope' => $request->non_compete_geographic_scope,
            'confidentiality_duration_years' => $request->confidentiality_duration_years,
            'jurisdiction'             => $request->jurisdiction,
            'generated_date'           => $today,
            'leave_types'              => $request->leave_types ?? [],
        ];

        $documents = [];

        foreach ($request->documents as $type) {
            switch ($type) {
                case 'offer_letter':
                    $documents[] = $this->generateOfferLetter($data);
                    break;
                case 'nda':
                    $documents[] = $this->generateNDA($data);
                    break;
                case 'appointment_letter':
                    $documents[] = $this->generateAppointmentLetter($data);
                    break;
                case 'employment_contract':
                    $documents[] = $this->generateEmploymentContract($data);
                    break;
                case 'non_compete':
                    $documents[] = $this->generateNonCompete($data);
                    break;
                case 'leave_policy':
                    $documents[] = $this->generateLeavePolicy($data);
                    break;
            }
        }

        return view('admin.documents.preview', compact('documents', 'data'));
    }

